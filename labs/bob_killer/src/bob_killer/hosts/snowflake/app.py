"""The Streamlit app's deploy SQL, from the ``app`` entity of hosts/snowflake/snowflake.yml.

Snowflake CLI 3.29 refuses artifact sources outside the project root (symlinks included), and
the app package lives in src/bob_killer_sis/. So the deploy copies the entity's artifacts to
``@APP_SRC`` (created by 20_compiler_objects.sql; ``--artifacts`` lists them) and creates the
app with ``50_app.sql``, rendered here from the same entity: name, title, warehouse, container
runtime, compute pool, integrations.

``uv run python -m bob_killer.hosts.snowflake.app`` rewrites the SQL file.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

HOST = Path(__file__).resolve().parents[4] / "hosts" / "snowflake"
SQL_PATH = HOST / "sql" / "50_app.sql"
STAGE = "APP_SRC"
ENTITY = "app"


def entity() -> dict[str, Any]:
    definition: dict[str, Any] = yaml.safe_load((HOST / "snowflake.yml").read_text("utf-8"))
    app: dict[str, Any] = definition["entities"][ENTITY]
    return app


def render_ddl() -> str:
    app = entity()
    integrations = ", ".join(app["external_access_integrations"])
    title = app["title"].replace("'", "''")
    return (
        "-- Generated by `uv run python -m bob_killer.hosts.snowflake.app`; do not edit.\n"
        f"-- Run after hosts/snowflake/deploy.sh copied the app artifacts to @{STAGE}.\n"
        f"CREATE OR REPLACE STREAMLIT {app['identifier']['name']}\n"
        f"  FROM '@{STAGE}'\n"
        f"  MAIN_FILE = '{app['main_file']}'\n"
        f"  TITLE = '{title}'\n"
        f"  QUERY_WAREHOUSE = {app['query_warehouse']}\n"
        f"  RUNTIME_NAME = '{app['runtime_name']}'\n"
        f"  COMPUTE_POOL = {app['compute_pool']}\n"
        f"  EXTERNAL_ACCESS_INTEGRATIONS = ({integrations});\n"
    )


def artifacts() -> tuple[tuple[Path, str], ...]:
    """(source file, name on @APP_SRC) for every artifact of the entity."""
    return tuple(((HOST / a["src"]).resolve(), a["dest"]) for a in entity()["artifacts"])


if __name__ == "__main__":
    import sys

    if sys.argv[1:] == ["--artifacts"]:
        print("\n".join(f"{src} {dest}" for src, dest in artifacts()))
    else:
        SQL_PATH.write_text(render_ddl(), encoding="utf-8")
