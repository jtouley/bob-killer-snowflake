"""``RUN_PIPELINE(run_id)``: the whole compiler pipeline in one caller's-rights procedure.

``EXECUTE DBT PROJECT`` fails inside an owner's-rights procedure and runs in a caller's-rights
one (F15, checked in a TEST_ schema on 2026-10-27), so RUN_PIPELINE is ``EXECUTE AS CALLER``.
The snowflake.yml procedures stay owner's rights (D1); this one is created from
``hosts/snowflake/sql/40_run_pipeline.sql`` after ``snow snowpark deploy``, importing the same
build zip and the packages of requirements.txt through the artifact repository (F3).

``uv run python -m bob_killer.hosts.snowflake.run_pipeline`` rewrites the SQL file.
"""

from __future__ import annotations

from pathlib import Path

from bob_killer.hosts.snowflake.udfs import IMPORTS, RUNTIME_VERSION

NAME = "RUN_PIPELINE"
ARGUMENTS = ("RUN_ID VARCHAR",)
HANDLER = "bob_killer.hosts.snowflake.procedure.run_pipeline_procedure"
ARTIFACT_REPOSITORY = "snowflake.snowpark.pypi_shared_repository"
HOST = Path(__file__).resolve().parents[4] / "hosts" / "snowflake"
REQUIREMENTS = HOST / "requirements.txt"
SQL_PATH = HOST / "sql" / "40_run_pipeline.sql"


def packages() -> tuple[str, ...]:
    lines = REQUIREMENTS.read_text(encoding="utf-8").splitlines()
    return tuple(line.strip() for line in lines if line.strip() and not line.startswith("#"))


def render_ddl() -> str:
    listed = ", ".join(f"'{p}'" for p in packages())
    return (
        "-- Generated by `uv run python -m bob_killer.hosts.snowflake.run_pipeline`; do not edit.\n"
        "-- Run in the deployment schema after `snow snowpark deploy` (the build zip).\n"
        f"CREATE OR REPLACE PROCEDURE {NAME}({', '.join(ARGUMENTS)})\n"
        "  RETURNS VARIANT\n"
        "  LANGUAGE PYTHON\n"
        f"  RUNTIME_VERSION = '{RUNTIME_VERSION}'\n"
        f"  ARTIFACT_REPOSITORY = {ARTIFACT_REPOSITORY}\n"
        f"  PACKAGES = ({listed})\n"
        f"  IMPORTS = ('{IMPORTS}')\n"
        f"  HANDLER = '{HANDLER}'\n"
        "  EXECUTE AS CALLER;\n"
    )


if __name__ == "__main__":
    SQL_PATH.write_text(render_ddl(), encoding="utf-8")
