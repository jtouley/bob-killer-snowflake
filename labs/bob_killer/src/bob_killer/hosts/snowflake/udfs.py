"""Python UDFs over the core runtime (docs/SPEC-compiler-dbt.md §4.4, D20, D21).

One UDF per entry of ``registry.functions``: ``BK_OP_<op>`` for a runtime operator ``OP_<op>``,
``BK_FN_<NAME>`` (dots as ``_``) for an Excel function. Each takes one ``ARRAY``: the call's
positional arguments as wire objects (a range is ``{"cols", "cells"}``, ``runtime.wire``), so a
variadic function needs no overload per arity. Each handler decodes the arguments, calls the
runtime and returns the result as a wire object. ``BK_VALUES_EQUAL`` wraps
``verify.config.values_equal``; ``BK_WIRE_DECODE_NUMBER`` is for display only, never parity.

The DDL comes from the registry only: ``uv run python -m bob_killer.hosts.snowflake.udfs``
rewrites ``hosts/snowflake/sql/30_udfs.sql``. Handlers import the build zip (F8, F19).
"""

from __future__ import annotations

import json
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol

import bob_killer.runtime.functions  # noqa: F401  (registers the Excel functions and operators)
from bob_killer.contracts.ir import CellValue
from bob_killer.registry import functions
from bob_killer.runtime import wire
from bob_killer.verify.config import values_equal

RUNTIME_VERSION = "3.12"
IMPORTS = "@DEPLOYMENTS/src.zip/src.zip"  # snow snowpark deploy's layout (F8), schema-relative
PACKAGES = ("pydantic==2.11.9",)  # Snowflake Anaconda channel, py312 (F3, F21)
OPERATOR = "OP_"
VALUES_EQUAL = "BK_VALUES_EQUAL"
WIRE_DECODE_NUMBER = "BK_WIRE_DECODE_NUMBER"
MODULE = "bob_killer.hosts.snowflake.udfs"  # the handler path, also under `python -m`
SQL_PATH = Path(__file__).resolve().parents[4] / "hosts" / "snowflake" / "sql" / "30_udfs.sql"


@dataclass(frozen=True)
class Udf:
    name: str
    params: str
    returns: str
    handler: str


def udf_name(function: str) -> str:
    if function.startswith(OPERATOR):
        return f"BK_OP_{function.removeprefix(OPERATOR)}"
    return f"BK_FN_{function.replace('.', '_')}"


def handler_name(function: str) -> str:
    return "call_" + function.replace(".", "_")


def _plain(value: Any) -> Any:
    """JSON types only, for the VARIANT result."""
    return json.loads(json.dumps(value))


def call(function: str, args: list[Any]) -> Any:
    result = functions.get(function)(*(wire.decode_arg(a) for a in args))
    return _plain(wire.encode(result))  # type: ignore[arg-type]


def _handler(function: str) -> Callable[[list[Any]], Any]:
    def handler(args: list[Any]) -> Any:
        return call(function, args)

    handler.__name__ = handler_name(function)
    return handler


def bk_values_equal(expected: Any, actual: Any) -> bool:
    return values_equal(_cell(expected), _cell(actual))


def bk_wire_decode_number(value: Any) -> float | None:
    cell = _cell(value)
    return None if cell.h is None else float.fromhex(cell.h)


def _cell(value: Any) -> CellValue:
    return CellValue.model_validate_json(json.dumps(value))


_HOST = {
    VALUES_EQUAL: ("EXPECTED VARIANT, ACTUAL VARIANT", "BOOLEAN", bk_values_equal),
    WIRE_DECODE_NUMBER: ("VALUE VARIANT", "FLOAT", bk_wire_decode_number),
}

for _function in functions.names():
    globals()[handler_name(_function)] = _handler(_function)


def handler_of(udf: str) -> str:
    """The module attribute of a host UDF's handler."""
    return _HOST[udf][2].__name__


def udfs() -> tuple[Udf, ...]:
    module = MODULE
    runtime = tuple(
        Udf(udf_name(f), "ARGS ARRAY", "VARIANT", f"{module}.{handler_name(f)}")
        for f in functions.names()
    )
    host = tuple(
        Udf(name, params, returns, f"{module}.{fn.__name__}")
        for name, (params, returns, fn) in _HOST.items()
    )
    return runtime + host


def statements() -> tuple[str, ...]:
    packages = ", ".join(f"'{p}'" for p in PACKAGES)
    return tuple(
        f"CREATE OR REPLACE FUNCTION {u.name}({u.params})\n"
        f"  RETURNS {u.returns}\n"
        "  LANGUAGE PYTHON\n"
        "  IMMUTABLE\n"
        f"  RUNTIME_VERSION = '{RUNTIME_VERSION}'\n"
        f"  PACKAGES = ({packages})\n"
        f"  IMPORTS = ('{IMPORTS}')\n"
        f"  HANDLER = '{u.handler}'"
        for u in udfs()
    )


def render_ddl() -> str:
    head = (
        f"-- Generated by `uv run python -m {MODULE}` from registry.functions.\n"
        "-- Do not edit. Run in the deployment schema after `snow snowpark deploy`.\n"
    )
    return head + "".join(f"{s};\n" for s in statements())


class SqlSession(Protocol):
    def sql(self, query: str) -> Any: ...


def create_udfs(session: SqlSession) -> None:
    for statement in statements():
        session.sql(statement).collect()


if __name__ == "__main__":
    SQL_PATH.write_text(render_ddl(), encoding="utf-8")
