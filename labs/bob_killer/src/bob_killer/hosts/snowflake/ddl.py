"""The ``snowflake`` DDL dialect over ``SNOWFLAKE_TABLES`` (docs/SPEC.md §6.2, D2).

Every model column is NOT NULL; the primary key is informational (Snowflake does not enforce it).
Two dialect columns follow the model columns: ``_seq`` (insert order) and ``_written_at``.

uv run python -m bob_killer.hosts.snowflake.ddl   # writes 10_tables.sql, 20_compiler_objects.sql

``COMPILER_TABLES`` are the compiler's host tables; ``compiler_objects_sql`` adds the run file
stage ``DBT_SRC`` (docs/SPEC-compiler-dbt.md §3.4).
"""

from __future__ import annotations

from collections.abc import Iterable
from datetime import datetime
from enum import Enum
from pathlib import Path

from bob_killer.contracts import TABLES, StrictModel
from bob_killer.contracts.bronze import BronzeRow, LandedFile
from bob_killer.contracts.ddl import ddl_dialects
from bob_killer.contracts.report import EquivalenceReport
from bob_killer.contracts.workbook import WbInputCell

SNOWFLAKE_TABLES: tuple[type[StrictModel], ...] = (*TABLES, LandedFile, BronzeRow)
COMPILER_TABLES: tuple[type[StrictModel], ...] = (WbInputCell, EquivalenceReport)

_SCALARS: dict[object, str] = {
    str: "VARCHAR",
    int: "NUMBER(38,0)",
    float: "FLOAT",
    bool: "BOOLEAN",
    datetime: "TIMESTAMP_TZ",
}
DIALECT_COLUMNS: tuple[tuple[str, str], ...] = (
    ("_seq", "NUMBER AUTOINCREMENT ORDER"),
    ("_written_at", "TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()"),
)
GOLDEN = Path(__file__).resolve().parents[4] / "hosts/snowflake/sql/10_tables.sql"
COMPILER_OBJECTS = GOLDEN.with_name("20_compiler_objects.sql")
DBT_SRC_STAGE = (
    "-- Compiler objects of one deployment schema (docs/SPEC-compiler-dbt.md §3.4).\n"
    "-- Generated by `uv run python -m bob_killer.hosts.snowflake.ddl`; do not edit.\n"
    "-- Run as BOB_KILLER_OWNER in the deployment schema (APP or TEST_<uuid8>),\n"
    "-- after 10_tables.sql.\n"
    "-- DBT_SRC holds each run's files: @DBT_SRC/<run_id>/{workbook.db, ir.yaml, dbt/, docs/};\n"
    "-- @DBT_SRC/_reviews/ holds the name review files (hosts/snowflake/reviews/).\n"
    "CREATE STAGE IF NOT EXISTS DBT_SRC\n"
    "  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')\n"
    "  DIRECTORY = (ENABLE = TRUE);\n"
    "-- UPLOADS holds the uploaded workbooks as <sha256>.xlsx (docs/SPEC.md §6.3).\n"
    "CREATE STAGE IF NOT EXISTS UPLOADS\n"
    "  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')\n"
    "  DIRECTORY = (ENABLE = TRUE);\n"
    "-- APP_SRC holds the Streamlit app's files for 50_app.sql (hosts/snowflake/app.py).\n"
    "CREATE STAGE IF NOT EXISTS APP_SRC\n"
    "  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')\n"
    "  DIRECTORY = (ENABLE = TRUE);\n"
)


def column_type(name: str, annotation: object) -> str:
    if annotation in _SCALARS:
        return _SCALARS[annotation]
    if isinstance(annotation, type) and issubclass(annotation, Enum):
        return "VARCHAR"
    if isinstance(annotation, type) and issubclass(annotation, StrictModel):
        return "VARIANT"
    raise TypeError(f"no Snowflake mapping for {name}: {annotation!r}")


def table_ddl(model: type[StrictModel]) -> str:
    cols = [
        f"{name} {column_type(name, field.annotation)} NOT NULL"
        for name, field in model.model_fields.items()
    ]
    cols += [f"{name} {spec}" for name, spec in DIALECT_COLUMNS]
    cols.append(f"PRIMARY KEY ({', '.join(model.primary_key)})")
    body = ",\n  ".join(cols)
    return f"CREATE TABLE IF NOT EXISTS {model.table_name.upper()} (\n  {body}\n);\n"


def schema_ddl(models: Iterable[type[StrictModel]]) -> str:
    return "\n".join(table_ddl(m) for m in models)


ddl_dialects.setdefault("snowflake", schema_ddl)


def compiler_objects_sql() -> str:
    return DBT_SRC_STAGE + "\n" + schema_ddl(COMPILER_TABLES)


def main() -> int:
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(schema_ddl(SNOWFLAKE_TABLES), encoding="utf-8")
    COMPILER_OBJECTS.write_text(compiler_objects_sql(), encoding="utf-8")
    print(GOLDEN, COMPILER_OBJECTS)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
