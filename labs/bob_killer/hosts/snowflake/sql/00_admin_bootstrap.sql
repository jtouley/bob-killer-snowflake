-- RECONSTRUCTED from docs/SPEC.md §6.3; applied 2026-10-16
-- Admin bootstrap for the Bob Killer Snowflake host. Run once, as an admin role, by a person.
-- The build connection (bob_killer, role BOB_KILLER_OWNER) never runs this file.
-- Replace <PUBLIC_KEY_BODY> with the body of ~/.snowflake/keys/bob_killer_rsa.pub (no header lines).
-- This file grants no admin role to BOB_KILLER_SVC.

USE ROLE ACCOUNTADMIN;

-- Role
CREATE ROLE IF NOT EXISTS BOB_KILLER_OWNER;
GRANT ROLE BOB_KILLER_OWNER TO ROLE SYSADMIN;
GRANT ROLE BOB_KILLER_OWNER TO USER IDENTIFIER($MY_USER);  -- SET MY_USER = '<your user>'; first

-- Service user (key-pair only)
CREATE USER IF NOT EXISTS BOB_KILLER_SVC
  TYPE = SERVICE
  RSA_PUBLIC_KEY = '<PUBLIC_KEY_BODY>'
  DEFAULT_ROLE = BOB_KILLER_OWNER
  DEFAULT_WAREHOUSE = BOB_KILLER_WH;
GRANT ROLE BOB_KILLER_OWNER TO USER BOB_KILLER_SVC;

-- Compute
CREATE WAREHOUSE IF NOT EXISTS BOB_KILLER_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE BOB_KILLER_WH TO ROLE BOB_KILLER_OWNER;

CREATE COMPUTE POOL IF NOT EXISTS BOB_KILLER_POOL
  MIN_NODES = 1
  MAX_NODES = 1
  INSTANCE_FAMILY = CPU_X64_XS
  AUTO_SUSPEND_SECS = 600
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, MONITOR, OPERATE ON COMPUTE POOL BOB_KILLER_POOL TO ROLE BOB_KILLER_OWNER;

-- Database and the production deployment schema (D7: one schema per deployment)
CREATE DATABASE IF NOT EXISTS BOB_KILLER;
GRANT OWNERSHIP ON DATABASE BOB_KILLER TO ROLE BOB_KILLER_OWNER COPY CURRENT GRANTS;
CREATE SCHEMA IF NOT EXISTS BOB_KILLER.APP;
GRANT OWNERSHIP ON SCHEMA BOB_KILLER.APP TO ROLE BOB_KILLER_OWNER COPY CURRENT GRANTS;

-- PyPI access for the container-runtime app (F7)
CREATE NETWORK RULE IF NOT EXISTS BOB_KILLER.APP.PYPI_RULE
  MODE = EGRESS
  TYPE = HOST_PORT
  VALUE_LIST = ('pypi.org', 'files.pythonhosted.org');
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS BOB_KILLER_PYPI_EAI
  ALLOWED_NETWORK_RULES = (BOB_KILLER.APP.PYPI_RULE)
  ENABLED = TRUE;
GRANT USAGE ON INTEGRATION BOB_KILLER_PYPI_EAI TO ROLE BOB_KILLER_OWNER;

-- Account grant for the container runtime
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE BOB_KILLER_OWNER;
