CREATE TABLE IF NOT EXISTS RUNS (
  run_id VARCHAR NOT NULL,
  filename VARCHAR NOT NULL,
  sha256 VARCHAR NOT NULL,
  state VARCHAR NOT NULL,
  created_at TIMESTAMP_TZ NOT NULL,
  schema_version NUMBER(38,0) NOT NULL,
  _seq NUMBER AUTOINCREMENT ORDER,
  _written_at TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (run_id)
);

CREATE TABLE IF NOT EXISTS STAGE_STATUS (
  run_id VARCHAR NOT NULL,
  stage VARCHAR NOT NULL,
  state VARCHAR NOT NULL,
  detail VARCHAR NOT NULL,
  _seq NUMBER AUTOINCREMENT ORDER,
  _written_at TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (run_id, stage)
);

CREATE TABLE IF NOT EXISTS LANDED_FILES (
  file_sha256 VARCHAR NOT NULL,
  filename VARCHAR NOT NULL,
  stage_file VARCHAR NOT NULL,
  size_bytes NUMBER(38,0) NOT NULL,
  first_run_id VARCHAR NOT NULL,
  _seq NUMBER AUTOINCREMENT ORDER,
  _written_at TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (file_sha256)
);

CREATE TABLE IF NOT EXISTS BRONZE_ROWS (
  file_sha256 VARCHAR NOT NULL,
  sheet VARCHAR NOT NULL,
  row_number NUMBER(38,0) NOT NULL,
  run_id VARCHAR NOT NULL,
  payload VARIANT NOT NULL,
  _seq NUMBER AUTOINCREMENT ORDER,
  _written_at TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (file_sha256, sheet, row_number)
);
